"""Original deterministic 3D room renderer and action teacher.

All geometry, materials, pixels and action trajectories are generated by this
project. The renderer supplies training/evaluation truth and the browser demo's
initial view. It never supplies later observations to a neural rollout.
"""
from dataclasses import dataclass
import copy

import numpy as np


ACTIONS = ("wait", "forward", "backward", "left", "right", "interact")


@dataclass
class Box:
    center: np.ndarray
    half: np.ndarray
    color: np.ndarray
    yaw: float = 0.0
    texture: int = 0


class Room:
    """Two rooms separated by a persistent hinged door; units are arbitrary."""

    def __init__(self, scene_seed: int, episode_seed: int = 0, size: int = 64):
        if size < 16 or size % 8:
            raise ValueError("size must be a multiple of 8 and at least 16")
        self.scene_seed = int(scene_seed)
        self.episode_seed = int(episode_seed)
        self.size = int(size)
        rng = np.random.default_rng(self.scene_seed)
        self.width = float(rng.uniform(6.0, 7.5))
        self.depth = float(rng.uniform(7.0, 9.0))
        self.height = 2.8
        self.door_half = .7
        self.door_open = False
        self.wall_color = rng.uniform(.32, .82, 3).astype(np.float32)
        self.floor_color = rng.uniform(.25, .65, 3).astype(np.float32)
        self.door_color = rng.uniform(.3, .85, 3).astype(np.float32)
        self.boxes = []
        w, d, h = self.width / 2, self.depth / 2, self.height
        self._box([0, -.08, 0], [w, .08, d], self.floor_color, texture=1)
        self._box([0, h + .08, 0], [w, .08, d], self.wall_color * .72)
        for x in (-w, w):
            self._box([x, h/2, 0], [.08, h/2, d], self.wall_color)
        for z in (-d, d):
            self._box([0, h/2, z], [w, h/2, .08], self.wall_color * .85)
        side_half = (w - self.door_half) / 2
        for sign in (-1, 1):
            self._box([sign*(w+self.door_half)/2, h/2, 0],
                      [side_half, h/2, .09], self.wall_color * .92)
        self._box([0, 2.5, 0], [self.door_half, .3, .09], self.wall_color * .92)
        for sign, z in [(-1, -2.1), (1, 1.8), (-1, 2.7)]:
            height = float(rng.uniform(.45, 1.0))
            self._box([sign * rng.uniform(1.5, 2.2), height/2, z],
                      [rng.uniform(.25, .45), height/2, rng.uniform(.25, .45)],
                      rng.uniform(.15, .9, 3), yaw=float(rng.uniform(-.3, .3)))
        episode_rng = np.random.default_rng(self.episode_seed)
        self.x = float(episode_rng.uniform(-.18, .18))
        self.z = float(episode_rng.uniform(-1.8, -1.5))
        self.yaw = float(episode_rng.uniform(-.08, .08))
        self.camera_height = 1.15
        coords = (np.arange(size, dtype=np.float32) + .5) / size * 2 - 1
        self.grid_x, self.grid_y = np.meshgrid(coords, -coords)

    def _box(self, center, half, color, yaw=0., texture=0):
        self.boxes.append(Box(np.asarray(center, np.float32), np.asarray(half, np.float32),
                              np.asarray(color, np.float32), yaw, texture))

    def clone(self):
        return copy.deepcopy(self)

    def door_box(self):
        # The hinge stays at (-door_half, 0). Open rotates the leaf into room two.
        angle = -np.pi / 2 if self.door_open else 0.
        center = [-self.door_half + self.door_half*np.cos(angle), 1.1,
                  -self.door_half*np.sin(angle)]
        return Box(np.asarray(center, np.float32), np.asarray([self.door_half, 1.1, .055], np.float32),
                   self.door_color, float(angle), 2)

    def state(self):
        return {"scene_seed": self.scene_seed, "episode_seed": self.episode_seed,
                "x": self.x, "z": self.z, "yaw": self.yaw, "door_open": self.door_open}

    def _collides(self, x, z):
        radius = .14
        for box in self.boxes + [self.door_box()]:
            if box.center[1] + box.half[1] < .2 or box.center[1] - box.half[1] > 1.5:
                continue
            dx, dz = x - box.center[0], z - box.center[2]
            c, s = np.cos(box.yaw), np.sin(box.yaw)
            lx, lz = c*dx-s*dz, s*dx+c*dz
            if abs(lx) < box.half[0]+radius and abs(lz) < box.half[2]+radius:
                return True
        return False

    def step(self, action: int):
        if not isinstance(action, (int, np.integer)) or not 0 <= action < len(ACTIONS):
            raise ValueError("action must be an integer in [0,5]")
        if action in (1, 2):
            direction = 1 if action == 1 else -1
            nx = self.x + direction * .18 * np.sin(self.yaw)
            nz = self.z + direction * .18 * np.cos(self.yaw)
            if not self._collides(nx, nz):
                self.x, self.z = float(nx), float(nz)
        elif action == 3:
            self.yaw -= np.pi / 24
        elif action == 4:
            self.yaw += np.pi / 24
        elif action == 5:
            distance = np.hypot(self.x, self.z)
            facing = (-self.x*np.sin(self.yaw)-self.z*np.cos(self.yaw)) / max(distance, .001)
            if distance < 2.3 and facing > .35:
                self.door_open = not self.door_open
        return self.state()

    def render(self):
        """Return original RGB uint8 [3,H,W], with direct ray-box intersections."""
        origin = np.asarray([self.x, self.camera_height, self.z], np.float32)
        c, s = np.cos(self.yaw), np.sin(self.yaw)
        u, v = self.grid_x * .72, self.grid_y * .72
        rays = np.stack([s+c*u, v, c-s*u], -1)
        rays /= np.linalg.norm(rays, axis=-1, keepdims=True)
        nearest = np.full((self.size, self.size), np.inf, np.float32)
        rgb = np.zeros((self.size, self.size, 3), np.float32)
        light = np.asarray([-.4, .8, -.3], np.float32)
        light /= np.linalg.norm(light)
        for box in self.boxes + [self.door_box()]:
            bc, bs = np.cos(box.yaw), np.sin(box.yaw)
            delta = origin - box.center
            local_origin = np.asarray([bc*delta[0]-bs*delta[2], delta[1], bs*delta[0]+bc*delta[2]])
            local_rays = np.stack([bc*rays[..., 0]-bs*rays[..., 2], rays[..., 1],
                                   bs*rays[..., 0]+bc*rays[..., 2]], -1)
            safe = np.where(np.abs(local_rays) < 1e-8, 1e-8, local_rays)
            slab_a = (-box.half - local_origin) / safe
            slab_b = (box.half - local_origin) / safe
            enter = np.minimum(slab_a, slab_b).max(-1)
            leave = np.maximum(slab_a, slab_b).min(-1)
            distance = np.where(enter > .001, enter, leave)
            hit = (leave >= np.maximum(enter, .001)) & (distance < nearest)
            if not hit.any():
                continue
            point = local_origin + local_rays * distance[..., None]
            face = np.argmin(np.abs(np.abs(point) - box.half), axis=-1)
            normal = np.zeros_like(point)
            np.put_along_axis(normal, face[..., None], np.take_along_axis(np.sign(point), face[..., None], -1), -1)
            world_normal = np.stack([bc*normal[..., 0]+bs*normal[..., 2], normal[..., 1],
                                      -bs*normal[..., 0]+bc*normal[..., 2]], -1)
            shade = .5 + .5*np.maximum((world_normal*light).sum(-1), 0)
            if box.texture == 1:
                checks = (np.floor(point[..., 0]*1.6)+np.floor(point[..., 2]*1.6)).astype(np.int32) % 2
                shade *= .76 + .24*checks
            elif box.texture == 2:
                stripe = np.abs(point[..., 0]) < .055
                shade *= np.where(stripe, .64, 1.)
            color = box.color[None, None, :] * shade[..., None]
            # Non-hit intersections can lie far behind the camera. They are
            # masked below; clamp only their fog arithmetic to avoid overflow.
            fog = np.exp(-np.maximum(distance, 0)*.025)[..., None]
            color = color*fog + np.asarray([.10, .14, .19])*(1-fog)
            rgb[hit] = color[hit]
            nearest[hit] = distance[hit]
        return np.moveaxis(np.round(np.clip(rgb, 0, 1)*255).astype(np.uint8), -1, 0)
